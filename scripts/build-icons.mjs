// Builds docs/assets/icons.svg — one <symbol id="i-NAME"> per icon — from lucide-static (ISC license).
// Run after adding an icon: node scripts/build-icons.mjs
// Content icons (the ones editors and the AI can pick) must match ICONS in docs/js/shared/schema.js.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ICONS } from "../docs/js/shared/schema.js";

const LUCIDE = fileURLToPath(new URL("../node_modules/lucide-static/icons/", import.meta.url));
const OUT = fileURLToPath(new URL("../docs/assets/icons.svg", import.meta.url));

// our name -> lucide name
const CONTENT = {
  plane: "plane", hotel: "hotel", bed: "bed-double", house: "house", car: "car", route: "route", fuel: "fuel",
  ferris: "ferris-wheel", coaster: "roller-coaster", ship: "ship", anchor: "anchor", food: "utensils-crossed",
  coffee: "coffee", star: "star", ticket: "ticket", camera: "camera", landmark: "landmark", building: "building-2",
  bus: "bus", train: "train-front", pin: "map-pin", shield: "shield-check", passport: "id-card", luggage: "luggage",
  baby: "baby", palm: "tree-palm", sun: "sun", bag: "shopping-bag", gift: "gift", phone: "smartphone",
  wallet: "wallet", map: "map",
};
const UI = {
  back: "arrow-right", next: "chevron-left", share: "share-2", print: "printer", check: "check",
  done: "circle-check-big", alert: "circle-alert", info: "info", edit: "pencil", plus: "plus", mic: "mic",
  speak: "volume-2", upload: "upload", file: "file-text", lock: "lock", login: "log-in", logout: "log-out",
  user: "user", users: "users", home: "house", history: "history", settings: "settings", copy: "copy",
  archive: "archive", undo: "undo-2", eye: "eye", close: "x", sparkles: "sparkles", send: "send",
  chat: "message-circle", calendar: "calendar", clock: "clock", list: "list-checks", up: "arrow-up",
  down: "arrow-down", trash: "trash-2", refresh: "refresh-cw", external: "external-link",
};

const missing = ICONS.filter((n) => !CONTENT[n]);
if (missing.length) throw new Error(`schema ICONS without a lucide mapping: ${missing.join(", ")}`);

const symbols = [];
for (const [name, lucide] of Object.entries({ ...CONTENT, ...UI })) {
  const svg = readFileSync(`${LUCIDE}${lucide}.svg`, "utf8");
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/\s*\n\s*/g, "")
    .trim();
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`);
}

const out = `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
<!-- Icons from Lucide (https://lucide.dev), ISC license. Generated by scripts/build-icons.mjs -->
${symbols.join("\n")}
</svg>
`;
writeFileSync(OUT, out);
console.log(`wrote ${symbols.length} icons to docs/assets/icons.svg (${out.length} bytes)`);
